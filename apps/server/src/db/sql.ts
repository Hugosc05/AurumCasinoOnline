/**
 * Traducción del SQL de la aplicación (escrito para SQLite con parámetros `?`)
 * al dialecto de PostgreSQL. El SQL de las consultas ya es portable; aquí solo
 * se ajusta lo que difiere en la sintaxis:
 *
 *  - parámetros `?` → `$1, $2…` (sin tocar el interior de los literales);
 *  - alias en camelCase (`AS createdAt`) entre comillas, porque PostgreSQL
 *    pasa a minúsculas los identificadores sin comillas;
 *  - en las migraciones, tipos de SQLite (AUTOINCREMENT, COLLATE NOCASE) a sus
 *    equivalentes (IDENTITY, citext) e INTEGER → BIGINT.
 */

const cache = new Map<string, string>();

/** Sustituye los literales '…' por marcadores para poder transformar el resto sin riesgo. */
function maskStrings(sql: string): { masked: string; strings: string[] } {
  const strings: string[] = [];
  const masked = sql.replace(/'(?:[^']|'')*'/g, (m) => {
    strings.push(m);
    return `\u0000${strings.length - 1}\u0000`;
  });
  return { masked, strings };
}

const unmask = (sql: string, strings: string[]): string => sql.replace(/\u0000(\d+)\u0000/g, (_m, i: string) => strings[Number(i)]!);

export function toPostgres(sql: string): string {
  const hit = cache.get(sql);
  if (hit !== undefined) return hit;
  const { masked, strings } = maskStrings(sql);
  let n = 0;
  let out = masked.replace(/\?/g, () => `$${(n += 1)}`);
  out = out.replace(/\bAS\s+([a-z][a-z0-9]*[A-Z][A-Za-z0-9]*)\b/g, 'AS "$1"');
  out = out.replace(/\bBEGIN IMMEDIATE\b/gi, 'BEGIN');
  const result = unmask(out, strings);
  if (cache.size < 2000) cache.set(sql, result);
  return result;
}

/** Traduce una migración escrita para SQLite al DDL equivalente de PostgreSQL. */
export function migrationToPostgres(sql: string): string {
  const { masked, strings } = maskStrings(sql.replace(/--[^\n]*/g, ''));
  let out = masked
    .replace(/\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b/gi, 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
    .replace(/\bTEXT\b([^,\n]*?)\s+COLLATE\s+NOCASE\b/gi, 'CITEXT$1')
    .replace(/\bINTEGER\b/g, 'BIGINT');
  out = out.replace(/^\s*PRAGMA[^;]*;\s*$/gim, '');
  return unmask(out, strings);
}
