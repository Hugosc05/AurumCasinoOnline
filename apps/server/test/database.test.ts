import { afterEach, describe, expect, it } from 'vitest';
import { loadConfig } from '../src/config';
import { migrationToPostgres, toPostgres } from '../src/db/sql';

describe('traducción de SQL a PostgreSQL', () => {
  it('numera los parámetros sin tocar los literales y protege los alias en camelCase', () => {
    expect(toPostgres(`SELECT a AS createdAt, '¿?' AS q FROM t WHERE x = ? AND y LIKE 'a?b' AND z = ?`)).toBe(
      `SELECT a AS "createdAt", '¿?' AS q FROM t WHERE x = $1 AND y LIKE 'a?b' AND z = $2`,
    );
    expect(toPostgres(`SELECT 'it''s ?' AS s, ? AS v`)).toBe(`SELECT 'it''s ?' AS s, $1 AS v`);
    expect(toPostgres('BEGIN IMMEDIATE')).toBe('BEGIN');
  });

  it('adapta el DDL de las migraciones', () => {
    const out = migrationToPostgres(`-- comentario con ' y ?
CREATE TABLE u (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  username TEXT NOT NULL COLLATE NOCASE UNIQUE,
  n INTEGER NOT NULL DEFAULT 0
);`);
    expect(out).toContain('id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY');
    expect(out).toContain('username CITEXT NOT NULL UNIQUE');
    expect(out).toContain('n BIGINT NOT NULL DEFAULT 0');
    expect(out).not.toContain('comentario');
  });
});

describe('configuración de la base de datos', () => {
  const saved = { ...process.env };
  afterEach(() => {
    process.env = { ...saved };
  });

  it('usa PostgreSQL con DATABASE_URL y SQLite sin ella', () => {
    expect(loadConfig({ NODE_ENV: 'development', DATABASE_URL: 'postgresql://u:p@db.example.com:5432/postgres' }).dbTarget).toMatch(/^postgresql:/);
    expect(loadConfig({ NODE_ENV: 'development', DATABASE_URL: '' }).dbTarget).toMatch(/aurum\.db$/);
    expect(() => loadConfig({ DATABASE_URL: 'mysql://x' })).toThrow(/DATABASE_URL/);
  });

  it('las pruebas nunca usan una base de datos real definida en el entorno', () => {
    process.env.DATABASE_URL = 'postgresql://u:p@db.example.com:5432/postgres';
    expect(loadConfig({ NODE_ENV: 'test' }).dbTarget).not.toMatch(/^postgresql:/);
  });

  it('Render: su dirección pública se admite como origen y activa el keep-alive', () => {
    const c = loadConfig({ NODE_ENV: 'production', RENDER_EXTERNAL_URL: 'https://aurum.onrender.com/' });
    expect(c.allowedOrigins).toContain('https://aurum.onrender.com');
    expect(c.keepAliveUrl).toBe('https://aurum.onrender.com/api/health');
    expect(loadConfig({ NODE_ENV: 'production', RENDER_EXTERNAL_URL: 'https://aurum.onrender.com', KEEPALIVE: 'false' }).keepAliveUrl).toBeNull();
    expect(loadConfig({ NODE_ENV: 'development' }).keepAliveUrl).toBeNull();
  });
});
